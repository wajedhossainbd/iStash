// Generates prototype/tokens.css from tokens.json and fails if any listed pair misses WCAG AA.
// Usage: node design/tokens.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('.', import.meta.url);
const t = JSON.parse(readFileSync(new URL('tokens.json', dir), 'utf8'));
const v = (name) => '--' + name.replace(/\./g, '-');

// Contrast: alpha colours are composited over the pair's background first.
const parse = (c) => {
  if (c.startsWith('#')) return [0, 2, 4].map((i) => parseInt(c.slice(1 + i, 3 + i), 16)).concat(1);
  const [r, g, b, a = 1] = c.match(/[\d.]+/g).map(Number);
  return [r, g, b, a];
};
const over = (fg, bg) => fg.slice(0, 3).map((x, i) => x * fg[3] + bg[i] * (1 - fg[3]));
const lum = (rgb) => {
  const [r, g, b] = rgb.map((x) => { x /= 255; return x <= 0.03928 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4; });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
export const ratio = (fg, bg) => {
  const b = parse(bg), f = over(parse(fg), b);
  const [x, y] = [lum(f), lum(b.slice(0, 3))];
  return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05);
};
console.assert(Math.abs(ratio('#000000', '#FFFFFF') - 21) < 0.01, 'contrast self-check');

let failed = 0;
for (const theme of ['light', 'dark']) {
  const c = t.color[theme];
  for (const [kind, min] of [['text', 4.5], ['graphic', 3]]) {
    for (const [fg, bg] of t.contrast[kind]) {
      const r = ratio(c[fg], c[bg]);
      if (r < min) { failed++; console.log(`FAIL ${theme} ${fg} on ${bg}: ${r.toFixed(2)} < ${min}`); }
    }
  }
}

const block = (obj) => Object.entries(obj).map(([k, val]) => `  ${v(k)}: ${val};`).join('\n');
const px = (obj, prefix) => Object.entries(obj).filter(([k]) => !k.startsWith('$')).map(([k, val]) => `  --${prefix}-${k}: ${val}px;`).join('\n');
const type = Object.entries(t.type).map(([k, s]) =>
  `  --type-${k}: ${s.weight} ${s.size}px/${s.line}px var(--font-${s.family});\n  --tracking-${k}: ${s.tracking}em;`).join('\n');
const elev = (theme) => Object.entries(t.elevation[theme]).map(([k, val]) => `  --elevation-${k}: ${val};`).join('\n');
const m = t.motion;
const motion = Object.entries(m.duration).map(([k, d]) => `  --duration-${k}: ${d}ms;`).join('\n') + '\n' +
  Object.entries(m.easing).map(([k, e]) => `  --easing-${k}: ${e};`).join('\n');

const css = `/* Generated by design/tokens.mjs from design/tokens.json. Do not edit by hand. */
:root {
  --font-text: ${t.font.text};
  --font-mono: ${t.font.mono};
${type}
${px(t.space, 'space')}
${px(t.radius, 'radius')}
${motion}
${block(t.color.light)}
${elev('light')}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${block(t.color.dark).replace(/^/gm, '  ')}
${elev('dark').replace(/^/gm, '  ')}
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${block(t.color.dark)}
${elev('dark')}
  color-scheme: dark;
}
@media (prefers-reduced-motion: reduce) {
  :root { --duration-fast: 0ms; --duration-base: 0ms; --duration-slow: 0ms; --duration-cable: 0ms; }
}
`;
writeFileSync(new URL('prototype/tokens.css', dir), css);
console.log(failed ? `${failed} contrast failures` : 'tokens.css written; all contrast pairs pass AA');
process.exit(failed ? 1 : 0);
